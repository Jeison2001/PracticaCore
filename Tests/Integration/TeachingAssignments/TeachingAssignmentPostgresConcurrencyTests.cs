        private static string GetBasePostgresConnectionString()
        {
            var envConn = Environment.GetEnvironmentVariable("PEGI_TEST_PG_CONNECTION");
            if (!string.IsNullOrWhiteSpace(envConn))
                return envConn;

            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null)
            {
                var candidate = Path.Combine(dir.FullName, "Api", "appsettings.json");
                if (File.Exists(candidate))
                {
                    using var doc = JsonDocument.Parse(File.ReadAllText(candidate));
                    if (doc.RootElement.TryGetProperty("ConnectionStrings", out var cs))
                    {
                        if (cs.TryGetProperty("Default", out var defVal) && !string.IsNullOrWhiteSpace(defVal.GetString()))
                            return defVal.GetString()!;
                        if (cs.TryGetProperty("DefaultConnection", out var defConnVal) && !string.IsNullOrWhiteSpace(defConnVal.GetString()))
                            return defConnVal.GetString()!;
                    }
                }

                dir = dir.Parent;
            }

            throw new InvalidOperationException(
                "No se encontró la cadena de conexión PostgreSQL en PEGI_TEST_PG_CONNECTION ni en Api/appsettings.json.");
        }

        private static string BuildIsolatedSchemaConnectionString(string baseConnectionString, string schema)
        {
            var builder = new NpgsqlConnectionStringBuilder(baseConnectionString)
            {
                SearchPath = $"{schema},public",
                MinPoolSize = 0,
                MaxPoolSize = 20,
                Pooling = true
            };
            return builder.ConnectionString;
        }

        private static AppDbContext CreatePostgresContext(string schemaConnectionString)
        {
            var options = new DbContextOptionsBuilder<AppDbContext>()
                .UseNpgsql(schemaConnectionString)
                .Options;
            return new AppDbContext(options);
        }

        private static async Task<string> CreateEphemeralSchemaAsync(string baseConnectionString)
        {
            var schema = $"conc_test_{Guid.NewGuid():N}";
            await using var conn = new NpgsqlConnection(baseConnectionString);
            await conn.OpenAsync();

            await using var cmd = conn.CreateCommand();
            cmd.CommandText = $@"
CREATE SCHEMA ""{schema}"";
CREATE TABLE ""{schema}"".""TeachingAssignment"" (
    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""IdInscriptionModality"" integer NOT NULL,
    ""IdTeacher"" integer NOT NULL,
    ""IdTypeTeachingAssignment"" integer NOT NULL,
    ""IdTeacherResearchProfile"" integer NULL,
    ""RevocationDate"" timestamp with time zone NULL,
    ""IsConfirmed"" boolean NOT NULL DEFAULT false,
    ""IdUserCreatedAt"" integer NULL,
    ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT now(),
    ""IdUserUpdatedAt"" integer NULL,
    ""UpdatedAt"" timestamp with time zone NULL,
    ""OperationRegister"" character varying(250) NOT NULL DEFAULT '',
    ""StatusRegister"" boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX ""UkTeachingAssignment_Active""
    ON ""{schema}"".""TeachingAssignment"" (""IdInscriptionModality"", ""IdTeacher"", ""IdTypeTeachingAssignment"")
    WHERE ""StatusRegister"" = TRUE AND ""RevocationDate"" IS NULL;
";
            await cmd.ExecuteNonQueryAsync();
            return schema;
        }

        private static async Task DropEphemeralSchemaAsync(string baseConnectionString, string schemaConnectionString, string schema)
        {
            await using (var poolConn = new NpgsqlConnection(schemaConnectionString))
            {
                NpgsqlConnection.ClearPool(poolConn);
            }

            await using var conn = new NpgsqlConnection(baseConnectionString);
            await conn.OpenAsync();
            await using var cmd = conn.CreateCommand();
            cmd.CommandText = $@"DROP SCHEMA IF EXISTS ""{schema}"" CASCADE;";
            await cmd.ExecuteNonQueryAsync();
        }

        private static UnitOfWork CreateUnitOfWork(AppDbContext context)
        {
            return new UnitOfWork(
                context,
                new Mock<IMediator>().Object,
                NullLogger<UnitOfWork>.Instance);
        }

        [Fact]
        public async Task AcquireTeacherCargoQuotaLockAsync_HoldsAdvisoryLockUntilCommit_AndSerializesConcurrentTransactions()
        {
            var baseConnStr = GetBasePostgresConnectionString();
            var schema = await CreateEphemeralSchemaAsync(baseConnStr);
            var schemaConnStr = BuildIsolatedSchemaConnectionString(baseConnStr, schema);

            const int teacherId = 77001;
            const int typeId = 2;

            try
            {
                await using var ctx1 = CreatePostgresContext(schemaConnStr);
                var uow1 = CreateUnitOfWork(ctx1);
                var repo1 = new TeachingAssignmentRepository(ctx1);

                await using var tx1 = await uow1.BeginTransactionAsync();
                await using var lock1 = await repo1.AcquireTeacherCargoQuotaLockAsync(teacherId, typeId);

                var tx2AcquiredLock = new TaskCompletionSource<int>(TaskCreationOptions.RunContinuationsAsynchronously);
                var tx2AttemptStarted = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);

                var tx2Task = Task.Run(async () =>
                {
                    await using var ctx2 = CreatePostgresContext(schemaConnStr);
                    var uow2 = CreateUnitOfWork(ctx2);
                    var repo2 = new TeachingAssignmentRepository(ctx2);

                    await using var tx2 = await uow2.BeginTransactionAsync();
                    tx2AttemptStarted.TrySetResult(true);

                    // Debe bloquearse en pg_advisory_xact_lock hasta que tx1 haga CommitAsync
                    await using var lock2 = await repo2.AcquireTeacherCargoQuotaLockAsync(teacherId, typeId);

                    var observedCountAfterTx1Commit = await ctx2.Set<TeachingAssignment>()
                        .CountAsync(ta =>
                            ta.IdTeacher == teacherId &&
                            ta.IdTypeTeachingAssignment == typeId &&
                            ta.StatusRegister &&
                            ta.RevocationDate == null);

                    tx2AcquiredLock.TrySetResult(observedCountAfterTx1Commit);
                    await tx2.CommitAsync();
                    return observedCountAfterTx1Commit;
                });

                await tx2AttemptStarted.Task;
                // Dar tiempo para verificar que tx2 realmente permanece bloqueada mientras tx1 no hace CommitAsync
                var completedBeforeCommit = await Task.WhenAny(tx2Task, Task.Delay(300));
                completedBeforeCommit.Should().NotBe(tx2Task,
                    "pg_advisory_xact_lock debe retener a la segunda transacción hasta que la primera haga commit");

                await repo1.AddAsync(new TeachingAssignment
                {
                    IdInscriptionModality = 5001,
                    IdTeacher = teacherId,
                    IdTypeTeachingAssignment = typeId,
                    IsConfirmed = true,
                    RevocationDate = null,
                    StatusRegister = true,
                    OperationRegister = "PG_LOCK_WINNER",
                    CreatedAt = DateTimeOffset.UtcNow
                });
                await uow1.CommitAsync();
                await tx1.CommitAsync();

                var countSeenByTx2 = await tx2Task.WaitAsync(TimeSpan.FromSeconds(15));
                countSeenByTx2.Should().Be(1,
                    "al liberarse pg_advisory_xact_lock tras el commit de tx1, tx2 debe ver la asignación ya persistida");
            }
            finally
            {
                await DropEphemeralSchemaAsync(baseConnStr, schemaConnStr, schema);
            }
        }

        [Fact]
        public async Task TryConfirmAssignmentAtomicallyAsync_ConcurrentExecuteUpdateAsync_ReturnsTrueOnlyForSingleWinner()
        {
            var baseConnStr = GetBasePostgresConnectionString();
            var schema = await CreateEphemeralSchemaAsync(baseConnStr);
            var schemaConnStr = BuildIsolatedSchemaConnectionString(baseConnStr, schema);

            try
            {
                int assignmentId;
                await using (var setupCtx = CreatePostgresContext(schemaConnStr))
                {
                    var seeded = new TeachingAssignment
                    {
                        IdInscriptionModality = 6001,
                        IdTeacher = 77002,
                        IdTypeTeachingAssignment = 1,
                        IsConfirmed = false,
                        RevocationDate = null,
                        StatusRegister = true,
                        OperationRegister = "PRESELECTED",
                        CreatedAt = DateTimeOffset.UtcNow
                    };
                    setupCtx.Set<TeachingAssignment>().Add(seeded);
                    await setupCtx.SaveChangesAsync();
                    assignmentId = seeded.Id;
                }

                const int concurrency = 8;
                var startGate = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
                var tasks = Enumerable.Range(1, concurrency).Select(workerIdx => Task.Run(async () =>
                {
                    await using var ctx = CreatePostgresContext(schemaConnStr);
                    var repo = new TeachingAssignmentRepository(ctx);
                    await startGate.Task;

                    return await repo.TryConfirmAssignmentAtomicallyAsync(
                        assignmentId,
                        $"RATIFIED_BY_{workerIdx}",
                        DateTimeOffset.UtcNow,
                        userId: 900 + workerIdx);
                })).ToArray();

                startGate.TrySetResult(true);
                var results = await Task.WhenAll(tasks);

                results.Count(r => r).Should().Be(1,
                    "ExecuteUpdateAsync con filtro !IsConfirmed en PostgreSQL debe devolver rows == 1 solo al primer ganador");
                results.Count(r => !r).Should().Be(concurrency - 1);

                await using var verifyCtx = CreatePostgresContext(schemaConnStr);
                var finalEntity = await verifyCtx.Set<TeachingAssignment>()
                    .AsNoTracking()
                    .SingleAsync(ta => ta.Id == assignmentId);
                finalEntity.IsConfirmed.Should().BeTrue();
                finalEntity.OperationRegister.Should().StartWith("RATIFIED_BY_");
            }
            finally
            {
                await DropEphemeralSchemaAsync(baseConnStr, schemaConnStr, schema);
            }
        }

        [Fact]
        public async Task DuplicateActiveInsert_UniqueConstraintViolation23505_RollsBackAndRecoversOnSameContextWithout25P02()
        {
            var baseConnStr = GetBasePostgresConnectionString();
            var schema = await CreateEphemeralSchemaAsync(baseConnStr);
            var schemaConnStr = BuildIsolatedSchemaConnectionString(baseConnStr, schema);

            const int inscriptionId = 7001;
            const int teacherId = 77003;
            const int typeId = 2;

            try
            {
                int winnerId;
                await using (var setupCtx = CreatePostgresContext(schemaConnStr))
                {
                    var winner = new TeachingAssignment
                    {
                        IdInscriptionModality = inscriptionId,
                        IdTeacher = teacherId,
                        IdTypeTeachingAssignment = typeId,
                        IsConfirmed = true,
                        RevocationDate = null,
                        StatusRegister = true,
                        OperationRegister = "CONC_WINNER",
                        CreatedAt = DateTimeOffset.UtcNow
                    };
                    setupCtx.Set<TeachingAssignment>().Add(winner);
                    await setupCtx.SaveChangesAsync();
                    winnerId = winner.Id;
                }

                await using var ctx = CreatePostgresContext(schemaConnStr);
                var uow = CreateUnitOfWork(ctx);
                var repo = new TeachingAssignmentRepository(ctx);

                await using var transaction = await uow.BeginTransactionAsync();
                var duplicateEntity = new TeachingAssignment
                {
                    IdInscriptionModality = inscriptionId,
                    IdTeacher = teacherId,
                    IdTypeTeachingAssignment = typeId,
                    IsConfirmed = true,
                    RevocationDate = null,
                    StatusRegister = true,
                    OperationRegister = "CONC_DUPLICATE",
                    CreatedAt = DateTimeOffset.UtcNow
                };

                var duplicate23505Caught = false;
                await repo.AddAsync(duplicateEntity);
                try
                {
                    await uow.CommitAsync();
                }
                catch (DbUpdateException ex) when (ex.InnerException is PostgresException pgEx && pgEx.SqlState == "23505")
                {
                    duplicate23505Caught = true;
                    await repo.DeleteAsync(duplicateEntity);
                    await transaction.RollbackAsync();
                }

                duplicate23505Caught.Should().BeTrue(
                    "el índice único parcial UkTeachingAssignment_Active en PostgreSQL debe lanzar SqlState 23505");

                var recovered = await repo.GetFirstOrDefaultAsync(
                    ta => ta.IdInscriptionModality == inscriptionId
                          && ta.IdTeacher == teacherId
                          && ta.IdTypeTeachingAssignment == typeId
                          && ta.StatusRegister
                          && ta.RevocationDate == null,
                    CancellationToken.None);

                recovered.Should().NotBeNull(
                    "tras DeleteAsync + RollbackAsync, el mismo AppDbContext debe recuperarse sin error 25P02");
                recovered!.Id.Should().Be(winnerId);
                recovered.OperationRegister.Should().Be("CONC_WINNER");
            }
            finally
            {
                await DropEphemeralSchemaAsync(baseConnStr, schemaConnStr, schema);
            }
        }
